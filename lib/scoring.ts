import { QUESTIONS } from '@/data/questions'
import { RiskResult } from '@/types'

export const MAX_SCORE = 26

export function calculateScore(answers: number[]): number {
  return answers.reduce(
    (sum, answerIndex, i) => sum + (QUESTIONS[i]?.answers[answerIndex]?.points ?? 0),
    0,
  )
}

// Пороги й імовірності — з оригінальної шкали FINDRISC.
export function riskFor(score: number): RiskResult {
  if (score < 7)
    return {
      level: 'low',
      title: 'Низький ризик',
      odds: 'приблизно 1 з 100',
      text: 'Ваші звички працюють на вас. Підтримуйте рух і харчування — і перевіряйте цукор під час планових оглядів.',
      steps: [
        'Здавайте глюкозу натще раз на 3 роки (після 45 — щороку).',
        'Тримайте щоденну активність від 30 хвилин.',
        'Половина тарілки — овочі, чверть — білок, чверть — крупи.',
      ],
    }
  if (score <= 11)
    return {
      level: 'slight',
      title: 'Злегка підвищений ризик',
      odds: 'приблизно 1 з 25',
      text: 'Кілька факторів уже грають проти вас, але все ще легко змінюється. Невеликі зміни зараз дають найбільший ефект.',
      steps: [
        'Здайте глюкозу натще й глікований гемоглобін (HbA1c).',
        'Замініть солодкі напої на воду — це найпростіший крок із відчутною користю.',
        'Додайте 10 хвилин ходьби після кожного прийому їжі.',
      ],
    }
  if (score <= 14)
    return {
      level: 'moderate',
      title: 'Помірний ризик',
      odds: 'приблизно 1 з 6',
      text: 'Саме зараз варто діяти: зниження ваги на 5–7% і регулярний рух помітно зменшують шанс захворіти.',
      steps: [
        'Здайте HbA1c і глюкозу натще найближчим часом.',
        'Обговоріть результат тесту із сімейним лікарем.',
        'Почніть з харчування: курс пояснює метод тарілки без жорстких дієт.',
      ],
    }
  if (score <= 20)
    return {
      level: 'high',
      title: 'Високий ризик',
      odds: 'приблизно 1 з 3',
      text: 'Цей результат — привід не відкладати аналізи. Можливо, у вас уже є переддіабет, і його можна повернути назад.',
      steps: [
        'Цього тижня здайте HbA1c і глюкозу натще.',
        'Запишіться до сімейного лікаря або ендокринолога.',
        'Розберіться, як працюють цукор, їжа й рух — з цього починається контроль.',
      ],
    }
  return {
    level: 'very_high',
    title: 'Дуже високий ризик',
    odds: 'приблизно 1 з 2',
    text: 'Є висока ймовірність, що діабет або переддіабет уже розвивається. Не лякайтеся — але й не відкладайте.',
    steps: [
      'Якнайшвидше здайте HbA1c і глюкозу натще.',
      'Зверніться до ендокринолога з результатами.',
      'Вивчіть основи самоконтролю — це знадобиться за будь-якого діагнозу.',
    ],
  }
}
